#!/usr/bin/env bash
# Claude Code adapter: link the kit's core into ~/.claude, one link per file or skill, so `git pull` updates
# every device, and build ~/.claude/agents/review-<id>.md from core/reviewers/<id>.md plus Claude's header.
# The rules: core/rules/CLAUDE.md becomes ~/.claude/CLAUDE.md; it loads core/rules/AGENTS.md from beside itself.
# Usage: ./install.sh [--dry-run] [--force]
#   --dry-run  print what would happen, change nothing
#   --force    replace existing files; the old ones move to ~/.claude/kit-backups/<time>/
set -euo pipefail
shopt -s nullglob

ADAPTER="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
KIT="$(cd "$ADAPTER/../.." && pwd)"
DEST="$HOME/.claude"
BACKUP="$DEST/kit-backups/$(date +%Y%m%d-%H%M%S)"
REVIEWER_HEADER='tools: Read, Grep, Glob'   # read-only tools; the gate passes the model on every dispatch
GENERATED="# generated by ai-kit from"                       # marks a reviewer file this script owns
DRY_RUN=0
FORCE=0
for arg in "$@"; do
  case "$arg" in
    --dry-run) DRY_RUN=1 ;;
    --force) FORCE=1 ;;
    -h|--help) sed -n '2,7p' "$0"; exit 0 ;;
    *) echo "unknown option: $arg" >&2; exit 2 ;;
  esac
done

linked=0 built=0 kept=0 skipped=0 removed=0

run() { if (( DRY_RUN )); then echo "         would run: $*"; else "$@"; fi; }

make_room() {  # make_room <target under ~/.claude>: back up what is there, or fail when not --force
  local dst="$1" rel="${1#"$DEST"/}"
  [[ -e "$dst" || -L "$dst" ]] || return 0
  if (( ! FORCE )); then
    echo "skip     $rel (exists; --force replaces it)"
    skipped=$((skipped + 1))
    return 1
  fi
  echo "backup   $rel -> ${BACKUP#"$DEST"/}/$rel"
  run mkdir -p "$(dirname "$BACKUP/$rel")"
  run mv "$dst" "$BACKUP/$rel"
}

link() {  # link <source in the kit> <target under ~/.claude>
  local src="$1" dst="$2" rel="${2#"$DEST"/}"
  if [[ -L "$dst" && "$(readlink "$dst")" == "$src" ]]; then
    kept=$((kept + 1))
    return
  fi
  if [[ -L "$dst" && "$(readlink "$dst")" == "$KIT"/* ]]; then
    run rm "$dst"            # a link the kit made earlier, to another kit file: re-point it, nothing to back up
  else
    make_room "$dst" || return 0
  fi
  echo "link     $rel -> ${src#"$KIT"/}"
  run mkdir -p "$(dirname "$dst")"
  run ln -s "$src" "$dst"
  linked=$((linked + 1))
}

reviewer() {  # reviewer <core reviewer file> <agent file under ~/.claude>: the core text plus Claude's header
  local src="$1" dst="$2" rel="${2#"$DEST"/}" text
  text="$(awk -v hdr="$REVIEWER_HEADER" -v mark="$GENERATED ${src#"$KIT"/}; edit that file, then re-run install.sh" \
    'NR > 1 && !done && /^---$/ { print hdr; print mark; done = 1 } { print }' "$src")"
  if [[ -f "$dst" && ! -L "$dst" && "$(cat "$dst")" == "$text" ]]; then
    kept=$((kept + 1))
    return
  fi
  if ! grep -qs "^$GENERATED " "$dst"; then make_room "$dst" || return 0; fi
  echo "build    $rel <- ${src#"$KIT"/}"
  if (( DRY_RUN )); then
    echo "         would write: $dst"
  else
    mkdir -p "$(dirname "$dst")"
    printf '%s\n' "$text" > "$dst"
  fi
  built=$((built + 1))
}

# The repo groups things by topic; ~/.claude gets them flat, where Claude Code looks for them.
link "$KIT/core/rules/CLAUDE.md" "$DEST/CLAUDE.md"
link "$KIT/core/rules/DEV_FLOW.md" "$DEST/DEV_FLOW.md"
for f in "$KIT"/core/rules/docs/*.md; do link "$f" "$DEST/docs/$(basename "$f")"; done
for f in "$KIT"/core/reviewers/*.md; do reviewer "$f" "$DEST/agents/review-$(basename "$f")"; done
for f in "$KIT"/core/skills/*/*/SKILL.md; do
  d="$(dirname "$f")"
  link "$d" "$DEST/skills/$(basename "$d")"
done
for f in "$KIT"/core/commands/*.md; do link "$f" "$DEST/commands/$(basename "$f")"; done
for f in "$ADAPTER"/hooks/*.py; do link "$f" "$DEST/hooks/$(basename "$f")"; done

# Remove links into the kit whose source was deleted from the repo, and reviewers built from a deleted file.
while IFS= read -r l; do
  [[ "$(readlink "$l")" == "$KIT"/* && ! -e "$l" ]] || continue
  echo "unlink   ${l#"$DEST"/}"
  run rm "$l"
  removed=$((removed + 1))
done < <(find "$DEST" -maxdepth 2 -type l)
for f in "$DEST"/agents/review-*.md; do
  grep -qs "^$GENERATED " "$f" && [[ ! -e "$KIT/core/reviewers/${f##*/review-}" ]] || continue
  echo "remove   ${f#"$DEST"/}"
  run rm "$f"
  removed=$((removed + 1))
done

summary="$linked linked, $built built, $kept up to date, $skipped skipped, $removed removed"
(( DRY_RUN )) && summary="$summary (dry run: nothing changed)"
echo "$summary"
